// Zoomed crops of every menu so button/panel padding and text centring can be inspected.
//   QA_URL=http://localhost:5174/ node tools/qa/ui-zoom.mjs [tag]
import { chromium } from "playwright-core";
const URL = process.env.QA_URL ?? "http://localhost:5173/";
const tag = process.argv[2] ?? "now";
const b = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto(URL);
await p.evaluate(() => localStorage.setItem("spellbound-arena.v2", JSON.stringify({ version: 2, tutorialDone: true, bestWave: 3, bestTimeMs: 83000, bestScore: 420, settings: {} })));
await p.reload();
await p.waitForFunction(() => window.__game?.scene.isActive("Menu"), null, { timeout: 20000 });
await p.waitForTimeout(900);
const shot = (name, clip) => p.screenshot({ path: `qa-shots/ui_${tag}_${name}.png`, clip });
await shot("menu", { x: 70, y: 590, width: 250, height: 250 });
await p.evaluate(() => { const m = window.__game.scene.getScene("Menu"); m.scene.pause(); m.scene.launch("Settings", { from: "Menu" }); });
await p.waitForTimeout(500);
await shot("settings", { x: 0, y: 220, width: 390, height: 420 });
await p.evaluate(() => { window.__game.scene.stop("Settings"); window.__game.scene.resume("Menu"); });
await p.keyboard.press("Enter");
await p.waitForFunction(() => window.__game?.scene.isActive("Game"), null, { timeout: 20000 });
await p.waitForTimeout(600);
await shot("hud_top", { x: 0, y: 0, width: 390, height: 70 });
await shot("hud_bottom", { x: 0, y: 740, width: 390, height: 104 });
await p.evaluate(() => window.__game.scene.getScene("Game").pauseGame());
await p.waitForTimeout(500);
await shot("pause", { x: 0, y: 260, width: 390, height: 320 });
await p.keyboard.press("Escape");
await p.waitForTimeout(300);
await p.evaluate(() => { const g = window.__game.scene.getScene("Game"); g.spawner.enabled = false; g.spells.levels.nova = 1; g.xp.add(9); });
await p.waitForTimeout(2600);
await shot("upgrade", { x: 0, y: 80, width: 390, height: 460 });
await p.keyboard.press("1");
await p.waitForTimeout(600);
await p.evaluate(() => { const g = window.__game.scene.getScene("Game"); g.damagePlayer(9, 10, 0, true); });
await p.waitForTimeout(4200);
await shot("gameover", { x: 0, y: 200, width: 390, height: 420 });
console.log("errors:", errs.length ? errs.join(" | ") : "none");
await b.close();
